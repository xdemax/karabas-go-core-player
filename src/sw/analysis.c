static uint32_t isqrt64(uint64_t v) {
  uint64_t r = 0, bit = (uint64_t) 1 << 62;
  while (bit > v) bit >>= 2;
  while (bit) {
    if (v >= r + bit) { v -= r + bit; r = (r >> 1) + bit; }
    else r >>= 1;
    bit >>= 2;
  }
  return (uint32_t) r;
}

static int ilog2u(uint32_t v) {
  int n = 0;
  while (v > 1) { v >>= 1; n++; }
  return n;
}

// Fixed dB-like scale: a band level depends only on its own magnitude, never on the loudest band
// of the frame. The old auto-gain made the whole spectrum jump when one loud band appeared.
void analysis_bands(uint8_t *out, int n) {
  if (n > 32) n = 32;
  if (!an_enabled) { memset(out, 0, (size_t) n); return; }
  int start = an_wr & (AN_N - 1);
  int16_t x[AN_N];
  for (int i = 0; i < AN_N; i++)
    x[i] = (int16_t) (((int32_t) an_buf[(start + i) & (AN_N - 1)] * an_hann[i]) >> 15);

  for (int b = 0; b < n; b++) {
    int32_t c = an_coeff[b], s1 = 0, s2 = 0;
    for (int i = 0; i < AN_N; i++) {
      int64_t s0 = (int64_t) x[i] + (((int64_t) c * s1) >> 14) - s2;
      s2 = s1;
      s1 = (int32_t) s0;
    }
    int64_t m2 = (int64_t) s1 * s1 + (int64_t) s2 * s2 - (((int64_t) c * s1 * s2) >> 14);
    uint32_t m = m2 > 0 ? isqrt64((uint64_t) m2) : 0;
    int l = m ? ilog2u(m) : 0;
    int v = (l * 255) / 22;               // full scale Goertzel ~4M (l=22)
    out[b] = (uint8_t) (v < 0 ? 0 : (v > 255 ? 255 : v));
  }
}
